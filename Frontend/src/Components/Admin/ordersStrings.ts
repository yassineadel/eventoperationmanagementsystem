export function useOrdersStrings(): OrdersStrings {
  const { lang } = usePreferences()
  return lang === 'ar' ? ar : en
}

/** Numbers, money, dates and people-written copy in the current language. */
export function useOrdersFormat() {
  const { lang } = usePreferences()
  return useMemo(() => {
    const locale = lang === 'ar' ? 'ar-EG' : 'en-GB'
    const number = new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-US')
    const amount = new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
    const dateTime = new Intl.DateTimeFormat(locale, {
      day: 'numeric',
      month: lang === 'ar' ? 'long' : 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
      timeZone: 'UTC',
    })
    const time = new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit', hour12: false, timeZone: 'UTC' })
    // Any date shape reads as Cairo wall time; something unreadable shows a dash instead of crashing.
    const show = (format: Intl.DateTimeFormat) => (value: string | undefined) => {
      const wall = toWall(value)
      return wall ? format.format(wallDate(wall)) : '—'
    }
    const digits = (s: string) => (lang === 'ar' ? s.replace(/[0-9]/g, (d) => '٠١٢٣٤٥٦٧٨٩'[Number(d)]) : s)
    return {
      lang,
      num: (n: number) => number.format(n),
      money: (n: number) => (lang === 'ar' ? `${amount.format(n)} ج.م` : `EGP ${amount.format(n)}`),
      date: show(dateTime),
      time: show(time),
      /** Phone numbers keep their digit groups in order inside right-to-left text. */
      phone: (p: string) => (lang === 'ar' ? digits(p).replace(/ /g, '‎ ') : p),
      digits,
      text: (l: Localized) => l[lang === 'ar' ? 'ar' : 'en'],
    }
  }, [lang])
}

export function fillIn(template: string, values: Record<string, string>) {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => values[k] ?? '')
}
