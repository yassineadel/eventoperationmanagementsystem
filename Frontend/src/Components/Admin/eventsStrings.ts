export type EventToast = { kind: 'added' | 'saved' | 'deleted' | 'published' | 'cancelled' | 'tickets' | 'failed'; name: string; id: string }

export function eventToastText(t: EventsStrings, toast: EventToast) {
  if (toast.kind === 'failed') return t.failed
  const template = {
    added: t.toastAdded,
    saved: t.toastSaved,
    deleted: t.toastDeleted,
    published: t.toastPublished,
    cancelled: t.toastCancelled,
    tickets: t.toastTickets,
  }[toast.kind]
  return template.replace('{name}', toast.name)
}
